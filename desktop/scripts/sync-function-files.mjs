// Copies the shared code into the Edge Functions (supabase/functions/<name>/_shared), so `sync`,
// `connectors`, `commands` and `asr` run exactly the app's rules. Only relative import paths change: Deno needs the `.ts`.
// Run: npm run sync:function   (tests/unit/sync/function-files.test.ts checks the copies)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = path.join(root, 'src/shared');

const FUNCTIONS = {
  sync: [
    'sync-ops.ts',
    'learn-log.ts',
    'task-lines.ts',
    'folders.ts',
    'channels.ts',
    'transcription.ts',
    'page-images.ts',
    'sync/protocol.ts',
    'sync/server-core.ts',
    'sync/pg-store.ts',
    'sync/handler.ts',
    'sync/postgres-db.ts',
    'sync/file-rules.ts',
    'sync/file-bucket.ts',
  ],
  connectors: [
    'connectors/store.ts',
    'connectors/crypto.ts',
    'connectors/pg-store.ts',
    'connectors/protocol.ts',
    'connectors/google-oauth.ts',
    'connectors/core.ts',
    'connectors/handler.ts',
  ],
  commands: [
    'commands/protocol.ts',
    'commands/store.ts',
    'commands/pg-store.ts',
    'commands/groq.ts',
    'commands/core.ts',
    'commands/handler.ts',
  ],
  asr: [
    'asr/protocol.ts',
    'asr/wav-info.ts',
    'asr/store.ts',
    'asr/pg-store.ts',
    'asr/core.ts',
    'asr/elevenlabs.ts',
    'asr/handler.ts',
  ],
};

const HEADER = '// GENERATED by desktop/scripts/sync-function-files.mjs from desktop/src/shared — do not edit here.\n';

for (const [name, files] of Object.entries(FUNCTIONS)) {
  const out = path.join(root, '../supabase/functions', name, '_shared');
  for (const file of files) {
    const code = fs.readFileSync(path.join(src, file), 'utf8');
    const withExt = code.replace(/(from\s+['"])(\.{1,2}\/[^'"]+?)(['"])/g, (_, a, spec, b) =>
      spec.endsWith('.ts') ? `${a}${spec}${b}` : `${a}${spec}.ts${b}`,
    );
    const target = path.join(out, file);
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, withExt);
  }
  fs.writeFileSync(path.join(out, 'README.md'), HEADER.replace('// ', '') + '\nEdit the sources under desktop/src/shared, then run `npm run sync:function` in desktop/.\n');
  console.log(`copied ${files.length} files to ${path.relative(root, out)}`);
}
