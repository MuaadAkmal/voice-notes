// Copies the shared sync code into the `sync` Edge Function (supabase/functions/sync/_shared), so the
// server runs exactly the app's rules. Only relative import paths change: Deno needs the `.ts`.
// Run: npm run sync:function   (tests/unit/sync/function-files.test.ts checks the copies)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = path.join(root, 'src/shared');
const out = path.join(root, 'supabase/functions/sync/_shared');

const FILES = [
  'sync-ops.ts',
  'learn-log.ts',
  'task-lines.ts',
  'folders.ts',
  'channels.ts',
  'transcription.ts',
  'sync/protocol.ts',
  'sync/server-core.ts',
  'sync/pg-store.ts',
  'sync/handler.ts',
  'sync/postgres-db.ts',
];

const HEADER = '// GENERATED by scripts/sync-function-files.mjs from src/shared — do not edit here.\n';

for (const file of FILES) {
  const code = fs.readFileSync(path.join(src, file), 'utf8');
  const withExt = code.replace(/(from\s+['"])(\.{1,2}\/[^'"]+?)(['"])/g, (_, a, spec, b) =>
    spec.endsWith('.ts') ? `${a}${spec}${b}` : `${a}${spec}.ts${b}`,
  );
  const target = path.join(out, file);
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, withExt);
}
fs.writeFileSync(path.join(out, 'README.md'), HEADER.replace('// ', '') + '\nEdit the sources under src/shared, then run `npm run sync:function`.\n');
console.log(`copied ${FILES.length} files to ${path.relative(root, out)}`);
